"""Build the storm formation from the authored hull and the existing transport."""

from pathlib import Path

from PIL import Image, ImageDraw

ART = Path(__file__).resolve().parent
SITES = ART.parents[1] / "mods/noita_hideout/files/storm/sites"
SIZE = (512, 496)
STEEL = (64, 64, 65, 255)
WOOD = (65, 63, 36, 255)


def pack_squares(mask, color):
    # The engine's converter reliably covers inclusive squares. Store only
    # occupied cells so retirement leaves nearby terrain and room contents alone.
    cells = {i for i, pixel in enumerate(mask.get_flattened_data()) if pixel == color}
    width = mask.width
    tiles = []
    for start in sorted(cells):
        if start not in cells:
            continue
        y, x = divmod(start, width)
        side = 1
        while x + side < width and all(
            (y + side) * width + x + k in cells and (y + k) * width + x + side in cells
            for k in range(side + 1)
        ):
            side += 1
        for row in range(y, y + side):
            cells.difference_update(range(row * width + x, row * width + x + side))
        tiles.append(f"{{{x},{y},{side}}}")
    return tiles


def build():
    background = Image.new("RGBA", SIZE)
    mask = Image.new("RGBA", SIZE, (255, 255, 255, 0))
    hull = Image.open(ART / "SteelShip.png").convert("RGBA")
    assert hull.size == (512, 256)
    background.alpha_composite(hull)
    draw = ImageDraw.Draw(mask)

    # Coordinates are inclusive, in the original SteelShip.png. Gaps match
    # the artist's door shadows; wall art, furniture and rigging stay permeable.
    def deck(left, right, top, bottom, hatches=()):
        for a, b in hatches:
            draw.rectangle((left, top, a - 1, bottom), fill=STEEL)
            left = b + 1
        draw.rectangle((left, top, right, bottom), fill=STEEL)

    deck(41, 454, 4, 7)
    deck(41, 454, 48, 55, [(175, 195)])
    deck(41, 454, 97, 103, [(280, 300)])
    deck(62, 409, 127, 136, [(353, 373)])
    deck(62, 409, 179, 188, [(102, 120), (226, 244)])
    deck(75, 315, 233, 239, [(155, 173)])
    for left, right in [(41, 44), (451, 454)]:
        draw.rectangle((left, 8, right, 96), fill=STEEL)
    for left, right in [(65, 68), (403, 406)]:
        draw.rectangle((left, 137, right, 178), fill=STEEL)
    for left, right in [(76, 79), (311, 314)]:
        draw.rectangle((left, 189, right, 232), fill=STEEL)
    for left, right in [(120, 126), (174, 178), (228, 231), (348, 351)]:
        draw.rectangle((left, 137, right, 154), fill=STEEL)
    for left, right in [(132, 139), (191, 199), (251, 258)]:
        draw.rectangle((left, 189, right, 208), fill=STEEL)

    # Only the lower escort carries the ground anchor and its boarding steps.
    for name, dest in [("ship_background", background), ("ship_materials", mask)]:
        escort = Image.open(SITES / (name + ".png")).convert("RGBA")
        dest.alpha_composite(escort, (8, 324))
        dest.alpha_composite(escort.crop((0, 0, 160, 85)), (140, 253))
    background.save(SITES / "steel_fleet_background.png")
    mask.save(SITES / "steel_fleet_materials.png")
    lines = ["-- Generated by resources/Airships/build_steel_fleet.py.", "return {"]
    for name, color in [("steel_static", STEEL), ("wood_static", WOOD)]:
        tiles = pack_squares(mask, color)
        lines.append(f"    {name}={{")
        for i in range(0, len(tiles), 8):
            lines.append("        " + ", ".join(tiles[i:i + 8]) + ",")
        lines.append("    },")
    (SITES / "steel_fleet_solids.lua").write_text("\n".join([*lines, "}", ""]), encoding="utf-8")


if __name__ == "__main__":
    build()
