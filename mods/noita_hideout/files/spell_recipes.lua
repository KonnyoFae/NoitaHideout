-- The vanilla action table supplies spell types, full charges, sprites and unlock flags.
-- Names come from common.csv, with Chinese fallbacks for Meteorisade and Matosade.
-- An action may have a translation key or sprite filename different from its ID.
-- Salvage owns the prices so a newly made card always refunds exactly its essence cost.
local recipes={}

local function add(spellType,id,zh,en,uses,options)
    local key=NHEssences.byAction[id]
    local stem=id:lower()
    options=options or {}
    local card={id=id,x=0,y=0,item={uses_remaining=uses or -1},useDefaultPickups=true}
    recipes[#recipes+1]={id="spell_"..id,category="spell",spellType=spellType,facility="salvage",
        zh=zh,en=en,unlockFlag=options.unlock,inputs={},resources={[key]=NHEssences.values[id]},
        item={kind="spell",name="$action_"..(options.name or stem),
            icon="data/ui_gfx/gun_actions/"..(options.sprite or stem)..".png",card=card}}
end

